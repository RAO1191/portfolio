function setMenu(open) {
  const hdr = document.querySelector('.hdr');
  if (!hdr) return;
  hdr.classList.toggle('open', open);
  hdr.querySelector('.menu-btn').setAttribute('aria-expanded', open ? 'true' : 'false');
}
