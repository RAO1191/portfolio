  const link = e.target.closest('a[href]');
  if (link) { const href = link.getAttribute('href'); const ev = LINK_EVENTS.find(([pre]) => href.startsWith(pre)); if (ev) track(ev[1]); }
  const op = e.target.closest('.cap-open');
